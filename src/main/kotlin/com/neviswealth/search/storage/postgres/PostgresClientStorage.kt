package com.neviswealth.search.storage.postgres

import com.neviswealth.search.domain.client.Client
import com.neviswealth.search.domain.client.ClientAlreadyExistsException
import com.neviswealth.search.domain.client.ClientStorage
import jakarta.enterprise.context.ApplicationScoped
import jakarta.inject.Inject
import org.jetbrains.exposed.v1.core.Table
import org.jetbrains.exposed.v1.core.eq
import org.jetbrains.exposed.v1.exceptions.ExposedSQLException
import org.jetbrains.exposed.v1.javatime.timestampWithTimeZone
import org.jetbrains.exposed.v1.jdbc.Database
import org.jetbrains.exposed.v1.jdbc.ExposedConnectionImpl
import org.jetbrains.exposed.v1.jdbc.insert
import org.jetbrains.exposed.v1.jdbc.selectAll
import org.jetbrains.exposed.v1.jdbc.transactions.transaction
import java.util.UUID
import javax.sql.DataSource
import kotlin.uuid.Uuid

/**
 * Exposed DSL description of the clients table. Flyway owns the actual DDL —
 * this mapping only has to agree with V1__init.sql; it is never used to create
 * or alter the schema.
 */
internal object ClientsTable : Table("clients") {
    val id = uuid("id")
    val firstName = text("first_name")
    val lastName = text("last_name")
    val email = text("email")
    val description = text("description").nullable()
    val socialLinks = array<String>("social_links")
    val createdAt = timestampWithTimeZone("created_at")
}

/**
 * Simple client CRUD over Exposed's JDBC DSL on the injected Agroal DataSource.
 * Uniqueness stays where the schema puts it: the adapter lets the INSERT hit
 * the unique index and translates SQLSTATE 23505 instead of pre-checking email.
 */
@ApplicationScoped
class PostgresClientStorage
    @Inject
    constructor(
        private val dataSource: DataSource,
    ) : ClientStorage {
        private val database: Database by lazy {
            // Explicit registration keeps the JDBC provider reachable in the native image.
            Database.connect(dataSource, connectionAutoRegistration = ExposedConnectionImpl())
        }

        override fun create(
            firstName: String,
            lastName: String,
            email: String,
            description: String?,
            socialLinks: List<String>,
        ): Client {
            val id = UUID.randomUUID()
            val exposedId = id.toExposedUuid()
            return try {
                transaction(database) {
                    ClientsTable.insert {
                        it[ClientsTable.id] = exposedId
                        it[ClientsTable.firstName] = firstName
                        it[ClientsTable.lastName] = lastName
                        it[ClientsTable.email] = email
                        it[ClientsTable.description] = description
                        it[ClientsTable.socialLinks] = socialLinks
                    }
                    // created_at is generated by the DB; read it back in the same transaction.
                    val createdAt =
                        ClientsTable
                            .selectAll()
                            .where { ClientsTable.id eq exposedId }
                            .single()[ClientsTable.createdAt]
                    Client(id, firstName, lastName, email, description, socialLinks, createdAt)
                }
            } catch (e: ExposedSQLException) {
                if (e.sqlState == "23505") throw ClientAlreadyExistsException(email)
                throw e
            }
        }

        override fun findById(id: UUID): Client? {
            val exposedId = id.toExposedUuid()
            return transaction(database) {
                ClientsTable
                    .selectAll()
                    .where { ClientsTable.id eq exposedId }
                    .singleOrNull()
                    ?.let { row ->
                        Client(
                            id = id,
                            firstName = row[ClientsTable.firstName],
                            lastName = row[ClientsTable.lastName],
                            email = row[ClientsTable.email],
                            description = row[ClientsTable.description],
                            socialLinks = row[ClientsTable.socialLinks],
                            createdAt = row[ClientsTable.createdAt],
                        )
                    }
            }
        }

        // Exposed's uuid column type uses kotlin.uuid.Uuid; the domain keeps java.util.UUID.
        private fun UUID.toExposedUuid(): Uuid = Uuid.parse(toString())
    }
